import { subYears } from "date-fns";
import { TZDate } from "@date-fns/tz";
import { db } from "@/lib/db";
import type { CurrentUser } from "@/lib/session";
import { monthBuckets, previousRange, type DateRange } from "@/lib/dates";
import { Decimal, dec, money } from "@/lib/money";
import { cashFlow, incomeByCategory, spendingByCategory, spendingByMerchant, percentChange, type AggregateOptions } from "@/lib/finance/aggregate";
import { aggOpts, cashFlowSeries, getCategoryMap, loadTxns, rollUpToParents, toSlices, type LoadedTxn } from "@/server/services/analytics";
import { getBudgetsWithStatus, spentForBudget } from "@/server/services/budgets";
import { budgetPeriodAt, previousPeriod, baseAllocation } from "@/lib/finance/budget";
import { getDebts, getNetWorthHistory } from "@/server/services/planning";
import { normalizeMerchant } from "@/lib/finance/duplicates";

export interface ReportFilters {
  accountIds?: string[];
  categoryIds?: string[];
}

function weekly(txns: LoadedTxn[], from: Date, to: Date, tz: string, opts: AggregateOptions) {
  const out: { label: string; key: string; value: number }[] = [];
  let cur = new TZDate(from, tz);
  // align to Monday
  const dow = (cur.getDay() + 6) % 7;
  cur = new TZDate(cur.getFullYear(), cur.getMonth(), cur.getDate() - dow, tz);
  while (cur < to) {
    const next = new TZDate(cur.getFullYear(), cur.getMonth(), cur.getDate() + 7, tz);
    const cf = cashFlow(txns.filter((t) => t.date >= cur && t.date < next), opts);
    out.push({ label: cur.toLocaleDateString("en", { day: "numeric", month: "short" }), key: cur.toISOString().slice(0, 10), value: cf.expenses.toDecimalPlaces(2).toNumber() });
    cur = next;
  }
  return out;
}

export async function getReportData(user: CurrentUser, range: DateRange, filters: ReportFilters) {
  const p = user.prefs;
  const opts = aggOpts(p);
  const prefs = { baseCurrency: p.baseCurrency, timezone: p.timezone, includePending: p.includePending, excludeReimbursable: p.excludeReimbursable };
  const prev = previousRange(range);
  const lyFrom = subYears(range.from, 1);
  const lyTo = subYears(range.to, 1);
  const filter = { accountIds: filters.accountIds, categoryIds: filters.categoryIds };

  const [txns, prevTxns, lastYear, cats, subs, recurring, budgets, nwHistory, debts] = await Promise.all([
    loadTxns(user.id, range.from, range.to, filter),
    loadTxns(user.id, prev.from, prev.to, filter),
    loadTxns(user.id, lyFrom, lyTo, filter),
    getCategoryMap(user.id),
    db.subscription.findMany({ where: { userId: user.id }, select: { name: true, merchant: true } }),
    db.recurringTransaction.findMany({ where: { userId: user.id }, select: { id: true, name: true, merchant: true, type: true, amount: true, isVariable: true } }),
    getBudgetsWithStatus(user.id, p),
    getNetWorthHistory(user.id, prefs, 12),
    getDebts(user.id, prefs),
  ]);

  const cf = cashFlow(txns, opts);
  const prevCf = cashFlow(prevTxns, opts);
  const months = monthBuckets(range.from, range.to, range.tz);
  const monthly = cashFlowSeries(txns, range.from, range.to, range.tz, opts, true);

  // Year-over-year by month
  const yoy = months.map((m) => {
    const lyStart = subYears(m.start, 1);
    const lyEnd = subYears(m.end, 1);
    const cur = cashFlow(txns.filter((t) => t.date >= m.start && t.date < m.end), opts);
    const ly = cashFlow(lastYear.filter((t) => t.date >= lyStart && t.date < lyEnd), opts);
    return { label: m.label, thisYear: cur.expenses.toDecimalPlaces(2).toNumber(), lastYear: ly.expenses.toDecimalPlaces(2).toNumber() };
  });

  // Categories with comparison
  const catNow = rollUpToParents(spendingByCategory(txns, opts), cats);
  const catPrev = rollUpToParents(spendingByCategory(prevTxns, opts), cats);
  const catSlices = toSlices(catNow, cats).map((s) => ({
    ...s,
    amount: money(s.amount),
    prev: money(catPrev.get(s.categoryId) ?? 0),
    change: percentChange(catNow.get(s.categoryId) ?? 0, catPrev.get(s.categoryId) ?? 0),
  }));

  // Merchants
  const merchants = [...spendingByMerchant(txns, opts).entries()]
    .filter(([, v]) => v.total.gt(0))
    .sort((a, b) => b[1].total.comparedTo(a[1].total))
    .slice(0, 15)
    .map(([name, v]) => ({ name, total: money(v.total), count: v.count, average: money(v.count ? v.total.div(v.count) : 0) }));

  // Essential vs discretionary
  const rawCat = spendingByCategory(txns, opts);
  let essential = new Decimal(0);
  let discretionary = new Decimal(0);
  for (const [k, v] of rawCat) {
    const c = k ? cats.get(k) : undefined;
    const isEss = c ? c.isEssential || (c.parentId ? cats.get(c.parentId)?.isEssential : false) : false;
    if (isEss) essential = essential.plus(v);
    else discretionary = discretionary.plus(v);
  }

  // Recurring vs non-recurring: generated by a schedule, or paid to a known subscription/recurring merchant
  const recurringKeys = new Set([...subs.map((s) => normalizeMerchant(s.merchant || s.name)), ...recurring.map((r) => normalizeMerchant(r.merchant || r.name))].filter(Boolean));
  const isRecurring = (t: LoadedTxn) => !!t.recurringId || recurringKeys.has(normalizeMerchant(t.merchant || t.description));
  const recurringSpend = cashFlow(txns.filter(isRecurring), opts).expenses;
  const nonRecurringSpend = cf.expenses.minus(recurringSpend);

  // Subscription trend (charges from subscription merchants by month)
  const subKeys = new Set(subs.map((s) => normalizeMerchant(s.merchant || s.name)).filter(Boolean));
  const subTrend = months.map((m) => {
    const total = txns
      .filter((t) => t.date >= m.start && t.date < m.end && t.type === "EXPENSE" && t.baseAmount != null && subKeys.has(normalizeMerchant(t.merchant || t.description)))
      .reduce((a, t) => a.plus(dec(t.baseAmount).abs()), new Decimal(0));
    return { label: m.label, value: total.toDecimalPlaces(2).toNumber() };
  });

  // Income sources
  const incNow = incomeByCategory(txns, opts);
  const incSources = [...incNow.entries()]
    .map(([k, v]) => ({ name: k ? cats.get(k)?.name ?? "Uncategorized" : "Uncategorized", amount: money(v), icon: k ? cats.get(k)?.icon ?? "circle" : "circle-dashed", color: k ? cats.get(k)?.color ?? "other" : "other", percent: cf.income.isZero() ? 0 : v.div(cf.income).times(100).toDecimalPlaces(1).toNumber() }))
    .sort((a, b) => Number(b.amount) - Number(a.amount));
  const monthlyIncome = monthly.map((m) => m.income.toDecimalPlaces(2).toNumber());
  const fullMonths = monthlyIncome.slice(0, -1).length ? monthlyIncome.slice(0, -1) : monthlyIncome;
  const avgIncome = fullMonths.length ? fullMonths.reduce((a, b) => a + b, 0) / fullMonths.length : 0;
  const sd = fullMonths.length > 1 ? Math.sqrt(fullMonths.reduce((a, b) => a + (b - avgIncome) ** 2, 0) / fullMonths.length) : 0;
  const expectedMonthlyIncome = recurring.filter((r) => r.type === "INCOME").reduce((a, r) => a.plus(dec(r.amount)), new Decimal(0));

  // Budget adherence over the last 6 periods for monthly budgets
  const adherence: { name: string; periods: { label: string; percent: number | null }[] }[] = [];
  const histTxns = budgets.length ? await loadTxns(user.id, subYears(new Date(), 1), new Date()) : [];
  for (const b of budgets.filter((x) => x.budget.period !== "CUSTOM").slice(0, 8)) {
    const periods: { label: string; percent: number | null }[] = [];
    let per = budgetPeriodAt(b.budget, new Date(), p.timezone, p.weekStartsOn === 0 ? 0 : 1);
    const descendants = new Set<string>();
    if (b.budget.categoryId) {
      descendants.add(b.budget.categoryId);
      for (const c of cats.values()) if (c.parentId === b.budget.categoryId) descendants.add(c.id);
    }
    for (let i = 0; i < 6; i++) {
      const inP = histTxns.filter((t) => t.date >= per.start && t.date < per.end);
      const spent = spentForBudget(b.budget, inP, opts, descendants.size ? descendants : undefined);
      const alloc = baseAllocation(b.budget, cashFlow(inP, opts).income);
      periods.unshift({ label: new TZDate(per.start, p.timezone).toLocaleDateString("en", { month: "short" }), percent: alloc.gt(0) ? spent.div(alloc).times(100).toDecimalPlaces(0).toNumber() : null });
      const pp = previousPeriod(b.budget, per, p.timezone);
      if (!pp) break;
      per = pp;
    }
    adherence.push({ name: b.budget.name, periods });
  }

  return {
    range: { key: range.key, label: range.label, from: range.from.toISOString(), to: range.to.toISOString() },
    summary: {
      income: money(cf.income),
      expenses: money(cf.expenses),
      net: money(cf.net),
      refunds: money(cf.refunds),
      savingsRate: cf.savingsRate,
      incomeChange: percentChange(cf.income, prevCf.income),
      expenseChange: percentChange(cf.expenses, prevCf.expenses),
      prevLabel: `${new Date(prev.from).toLocaleDateString("en", { day: "numeric", month: "short", year: "numeric" })} – ${new Date(prev.to.getTime() - 1).toLocaleDateString("en", { day: "numeric", month: "short", year: "numeric" })}`,
      unconverted: cf.unconverted,
      count: cf.count,
    },
    monthly: monthly.map((m) => ({
      label: m.label,
      key: m.key,
      income: m.income.toDecimalPlaces(2).toNumber(),
      expenses: m.expenses.toDecimalPlaces(2).toNumber(),
      net: m.net.toDecimalPlaces(2).toNumber(),
      savingsRate: m.income.gt(0) ? m.net.div(m.income).times(100).toDecimalPlaces(1).toNumber() : null,
    })),
    weekly: weekly(txns, range.from, range.to, range.tz, opts),
    yoy,
    categories: catSlices,
    merchants,
    essential: { essential: money(essential), discretionary: money(discretionary) },
    recurringSplit: { recurring: money(recurringSpend), nonRecurring: money(nonRecurringSpend) },
    subTrend,
    income: {
      sources: incSources,
      averageMonthly: money(new Decimal(avgIncome.toFixed(2))),
      volatility: avgIncome > 0 ? Math.round((sd / avgIncome) * 1000) / 10 : null,
      expectedMonthly: money(expectedMonthlyIncome),
      hasVariable: recurring.some((r) => r.type === "INCOME" && r.isVariable),
    },
    adherence,
    netWorth: nwHistory.map((h) => ({ label: h.label, netWorth: h.netWorth.toDecimalPlaces(2).toNumber() })),
    debts: debts.rows.filter((d) => !d.closedAt).map((d) => ({ name: d.name, progress: d.progress, balance: money(d.balance), currency: d.currency })),
  };
}

export type ReportData = Awaited<ReturnType<typeof getReportData>>;
